package com.etendoerp.go.payment;

/**
 * Result of validating a payment token presented with a paid onboarding request.
 */
public enum PaymentOutcome {

  /** The token is well-formed and the payment is considered settled. */
  APPROVED,

  /** No token was supplied. */
  MISSING_TOKEN,

  /** A token was supplied but the payment provider rejected it. */
  DECLINED
}
